-- =====================================================================
-- 015_api_keys.sql - external REST API keys for the /v1/* consensus API
-- @table-version api_keys 1.0.0
--
-- Idempotent migration for existing deployments that must converge on
-- the schema declared in db/schema.sql without a full import. Mirrors
-- the CREATE TABLE block shipped there exactly, including the
-- @table-version annotation so MigrationManager upserts the matching
-- version into app_config after a successful apply.
--
-- Only the SHA-256 hex digest of each key is stored (key_hash). The
-- plaintext key is generated by App\Api\ApiKeyService, shown once to
-- the operator, and never persisted in any other column.
-- =====================================================================
CREATE TABLE IF NOT EXISTS api_keys (
    id           INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    label        VARCHAR(128) NOT NULL,
    key_hash     CHAR(64)     NOT NULL UNIQUE,
    prefix       VARCHAR(16)  NOT NULL,
    scopes       VARCHAR(191) NOT NULL DEFAULT 'full',
    rpm_limit    INT UNSIGNED NOT NULL DEFAULT 30,
    daily_limit  INT UNSIGNED NOT NULL DEFAULT 1000,
    expires_at   DATETIME     NULL,
    last_used_at DATETIME     NULL,
    revoked_at   DATETIME     NULL,
    created_at   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_api_keys_prefix    (prefix),
    INDEX idx_api_keys_revoked   (revoked_at),
    INDEX idx_api_keys_last_used (last_used_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
