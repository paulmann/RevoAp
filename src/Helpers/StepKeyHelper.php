<?php
/**
 * StepKeyHelper: deterministic safe normalisation of pipeline step keys.
 *
 * The DB column `council_steps.step_key` is bounded at VARCHAR(191) on
 * MySQL/utf8mb4 so the composite index `idx_steps_session_step_key`
 * stays within the 767-byte single-column index limit on legacy
 * MySQL 5.7 hosts. The v1.8.28 audit found that composite role keys
 * such as `solution-auditor@deepseek_deepseek_v4_pro` combined with
 * prefixes like `L2.round2.normalize.` can already exceed the previous
 * VARCHAR(64) limit and cause PIPELINE_FATAL: `SQLSTATE[22001]:
 * Data too long for column 'step_key'`.
 *
 * To stay safe even when role/model/cycle segments grow further this
 * helper:
 *
 *   • preserves short keys verbatim so existing UI tabs / loop
 *     detection / statistics keep working unchanged;
 *   • for keys that exceed {@see self::MAX_LEN} it returns a
 *     deterministic value of the form `<prefix>-<sha256:12>` where the
 *     prefix is the readable head of the original key and the suffix
 *     is the first 12 hexadecimal chars of a sha256 of the full key.
 *     Two different long keys cannot collapse onto the same truncated
 *     value (collisions require a 48-bit sha256 prefix collision).
 *
 * The helper deliberately does NOT log on every call. Truncation is
 * counted via {@see self::wasTruncated()} so the pipeline engine can
 * emit a single diagnostic event when it first happens in a session.
 *
 * @project  RevoAp
 * @author   Mikhail Deynekin <mikhail@deynekin.com>
 * @site     https://Deynekin.com
 * @email    mikhail@deynekin.com
 * @version  1.0.0
 * @since    2026-05-13
 */
declare(strict_types=1);

namespace App\Helpers;

final class StepKeyHelper
{
    /**
     * Maximum stored length for `council_steps.step_key` in v1.8.28+.
     * Matches the VARCHAR(191) column declared in db/schema.sql.
     */
    public const int MAX_LEN = 191;

    /** Length of the deterministic hash suffix appended on truncation. */
    public const int HASH_LEN = 12;

    /** Separator between the readable prefix and the hash suffix. */
    private const string HASH_SEP = '-';

    /**
     * Return a value that fits inside `council_steps.step_key`.
     *
     * Short keys (≤ MAX_LEN) are returned verbatim. Longer keys collapse
     * to `<head>-<sha256:HASH_LEN>` where the head is the readable
     * prefix of the original. The function is pure and deterministic
     * so the same long key always returns the same truncated value;
     * loop detection and step lookup therefore keep working.
     *
     * @param  string $stepKey  raw step key generated by the pipeline.
     * @param  int    $maxLen   optional override (used by tests).
     * @return string           safe value ≤ $maxLen bytes long.
     */
    public static function normalize(string $stepKey, int $maxLen = self::MAX_LEN): string
    {
        if ($maxLen < (self::HASH_LEN + 2)) {
            // Degenerate caller — return the hash only.
            return substr(hash('sha256', $stepKey), 0, max(1, $maxLen));
        }
        if (strlen($stepKey) <= $maxLen) {
            return $stepKey;
        }
        $hash      = substr(hash('sha256', $stepKey), 0, self::HASH_LEN);
        $headLimit = $maxLen - self::HASH_LEN - strlen(self::HASH_SEP);
        $head      = substr($stepKey, 0, $headLimit);
        // Strip a trailing dot/separator from the head so the joined
        // value reads cleanly (e.g. `L2.normalize.foo-` not `L2.normalize.foo.-`).
        $head      = rtrim($head, '.-_');
        if ($head === '') {
            $head = 'step';
        }
        return $head . self::HASH_SEP . $hash;
    }

    /**
     * True when {@see self::normalize()} would shorten the supplied key.
     * Cheap to call (no hashing) — uses byte length only.
     */
    public static function wasTruncated(string $stepKey, int $maxLen = self::MAX_LEN): bool
    {
        return strlen($stepKey) > $maxLen;
    }
}
